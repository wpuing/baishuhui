CREATE TABLE bsh_category (
    id               VARCHAR(32)  NOT NULL,
    name             VARCHAR(32)  NOT NULL,
    sort_no          INT          NOT NULL DEFAULT 0,
    enabled          INT          NOT NULL DEFAULT 1,
    create_time      TIMESTAMP    NOT NULL,
    create_user      VARCHAR(32)  NOT NULL,
    create_user_name VARCHAR(64)  NOT NULL,
    update_time      TIMESTAMP    NOT NULL,
    update_user      VARCHAR(32)  NOT NULL,
    deleted          INT          NOT NULL DEFAULT 0,
    delete_time      TIMESTAMP    NULL,
    area             VARCHAR(32)  NULL,
    data_year        INT          NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_bsh_category_name UNIQUE (name)
);

CREATE INDEX idx_bsh_category_enabled ON bsh_category (deleted, enabled, sort_no);

