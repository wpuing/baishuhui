-- V11: dynamic menu for merchant/consumer + permissions. ASCII-only for H2.

CREATE TABLE bsh_menu (
    id               VARCHAR(32)  NOT NULL,
    parent_id        VARCHAR(32)  NULL,
    client_type      VARCHAR(16)  NOT NULL,
    name             VARCHAR(64)  NOT NULL,
    path             VARCHAR(256) NULL,
    icon             VARCHAR(64)  NULL,
    sort_no          INT          NOT NULL DEFAULT 0,
    menu_type        VARCHAR(16)  NOT NULL,
    permission_code  VARCHAR(64)  NULL,
    visible          INT          NOT NULL DEFAULT 1,
    create_time      TIMESTAMP    NOT NULL,
    create_user      VARCHAR(32)  NOT NULL,
    create_user_name VARCHAR(64)  NOT NULL,
    update_time      TIMESTAMP    NOT NULL,
    update_user      VARCHAR(32)  NOT NULL,
    deleted          INT          NOT NULL DEFAULT 0,
    delete_time      TIMESTAMP    NULL,
    area             VARCHAR(32)  NULL,
    data_year        INT          NOT NULL,
    PRIMARY KEY (id)
);

CREATE INDEX idx_bsh_menu_client ON bsh_menu (deleted, client_type, sort_no, id);
CREATE INDEX idx_bsh_menu_parent ON bsh_menu (deleted, parent_id);

CREATE TABLE bsh_role_menu (
    role_id VARCHAR(32) NOT NULL,
    menu_id VARCHAR(32) NOT NULL,
    PRIMARY KEY (role_id, menu_id)
);

